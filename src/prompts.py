def emergency_card(safety: SafetyReport, language: str = "en") -> str:
    """Fixed-text emergency response. No model involved."""
    lang = language if language in _EMERGENCY_HEAD else "en"
    flags = [f for f in safety.red_flags if f.urgency == "EMERGENCY"] or safety.red_flags

    why = "\n".join(f"- {f.label_in(lang)}" for f in flags)
    steps = "\n".join(f"- {f.guidance_in(lang)}" for f in flags if f.guidance_in(lang))

    parts = [_EMERGENCY_HEAD[lang], f"{_EMERGENCY_WHY[lang]}\n{why}"]
    if steps:
        parts.append(f"{_EMERGENCY_WAIT[lang]}\n{steps}")
    parts.append(_EMERGENCY_TAIL[lang])
    return "\n\n".join(parts)


def crisis_card(language: str = "en") -> str:
    """Fixed-text response for self-harm risk. No model involved."""
    return _CRISIS.get(language, _CRISIS["en"])


