def restricted_note(restriction_id: str, language: str = "en") -> str:
    """Short user-facing decline used on the extractive path.

    The model path gets the full policy in its system prompt. Without a model
    the refusal still has to be said out loud, otherwise "which antibiotic
    should I take" is answered with a wall of antibiotic guidance and no
    acknowledgement that the question was declined.
    """
    variants = _RESTRICTED_NOTES.get(restriction_id, {})
    return variants.get(language) or variants.get("en", "")


